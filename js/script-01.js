        // 4. Lightbox Modal with Zoom In / Zoom Out & Pan
        const screenshotFiles = [
            'im1.png', 'im2.png', 'im3.png', 'im4.png', 'im5.png', 'im6.png', 'im7.png', 'im8.png', 'im9.png'
        ];

        let currentIndex = 0;
        let currentZoom = 1;
        let panX = 0, panY = 0;
        let isPanning = false;
        let startPanX = 0, startPanY = 0;

        const modal = document.getElementById('lightboxModal');
        const lightboxImg = document.getElementById('lightboxImg');
        const lightboxTitle = document.getElementById('lightboxTitle');
        const zoomLevelText = document.getElementById('zoomLevelText');
        const lightboxStage = document.getElementById('lightboxStage');

        function getScreenshotTitle(index) {
            const key = `sc${index + 1}Title`;
            return translations[currentLang][key];
        }

        function openLightbox(index) {
            currentIndex = index;
            updateLightboxImage();
            modal.classList.add('active');
            document.body.style.overflow = 'hidden';
        }

        function closeLightbox() {
            modal.classList.remove('active');
            document.body.style.overflow = 'auto';
            resetZoom();
        }

        function updateLightboxImage() {
            resetZoom();
            lightboxImg.src = screenshotFiles[currentIndex];
            lightboxTitle.textContent = getScreenshotTitle(currentIndex);
        }

        function updateLightboxLanguage() {
            lightboxTitle.textContent = getScreenshotTitle(currentIndex);
            const pct = Math.round(currentZoom * 100);
            zoomLevelText.textContent = `${formatNumberForLang(pct)}%`;
        }

        function switchImage(dir) {
            currentIndex = (currentIndex + dir + screenshotFiles.length) % screenshotFiles.length;
            updateLightboxImage();
        }

        function applyTransform() {
            lightboxImg.style.transform = `translate(${panX}px, ${panY}px) scale(${currentZoom})`;
            const pct = Math.round(currentZoom * 100);
            zoomLevelText.textContent = `${formatNumberForLang(pct)}%`;
        }

        function changeZoom(delta) {
            currentZoom = Math.min(Math.max(0.5, currentZoom + delta), 3.5);
            if (currentZoom === 1) {
                panX = 0;
                panY = 0;
            }
            applyTransform();
        }

        function resetZoom() {
            currentZoom = 1;
            panX = 0;
            panY = 0;
            applyTransform();
        }

        lightboxStage.addEventListener('wheel', (e) => {
            e.preventDefault();
            const delta = e.deltaY < 0 ? 0.2 : -0.2;
            changeZoom(delta);
        });

        lightboxStage.addEventListener('mousedown', (e) => {
            if (currentZoom <= 1) return;
            isPanning = true;
            startPanX = e.clientX - panX;
            startPanY = e.clientY - panY;
        });

        window.addEventListener('mousemove', (e) => {
            if (!isPanning) return;
            panX = e.clientX - startPanX;
            panY = e.clientY - startPanY;
            applyTransform();
        });

        window.addEventListener('mouseup', () => {
            isPanning = false;
        });

        window.addEventListener('keydown', (e) => {
            if (!modal.classList.contains('active')) return;
            if (e.key === 'Escape') closeLightbox();
            if (e.key === 'ArrowRight') switchImage(1);
            if (e.key === 'ArrowLeft') switchImage(-1);
            if (e.key === '+') changeZoom(0.25);
            if (e.key === '-') changeZoom(-0.25);
        });

