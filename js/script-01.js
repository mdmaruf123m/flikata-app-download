        function formatNumberForLang(numStr) {
            if (currentLang === 'en') return String(numStr);
            const bnDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
            return String(numStr).replace(/\d/g, d => bnDigits[d]);
        }

